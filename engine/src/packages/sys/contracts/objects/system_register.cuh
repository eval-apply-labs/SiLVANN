#ifndef SILVANN__PACKAGES_SYS_CONTRACTS_OBJECTS_SYSTEM_REGISTER_CUH
#define SILVANN__PACKAGES_SYS_CONTRACTS_OBJECTS_SYSTEM_REGISTER_CUH

/* What this file needs, named where a reader — and an editor — can follow it. */
#include <stdint.h>

/* ── THE ROWS ────────────────────────────────────────────────────────────────────────────────────────
 * One row per every thing the whole device has to be able to name. A row arrives with the code that reads
 * it and not before: a row with no reader cannot be checked by anything, and a register full of them is a
 * list nobody can tell the live entries in.
 *
 * ⛳ THE NAME IS WRITTEN OUT IN FULL IN EACH ROW RATHER THAN BUILT FROM A STEM. A name that is pasted
 * together exists in no file as the thing it becomes, so nothing that reads source — a search, a gate, a
 * person — can find it from the spelling they have. The list costs a few characters and the name stays
 * greppable, which is the trade this package makes everywhere else too.
 * ────────────────────────────────────────────────────────────────────────────────────────────────── */
/* ── THE ROWS, AND NOBODY NUMBERS THEM ───────────────────────────────────────────────────────────────
 * One row per thing the whole device has to be able to name. A row arrives with the code that reads it
 * and not before: a row with no reader cannot be checked by anything, and — `MEASURED`, by dropping one
 * — a row nothing reads is invisible to a suite that passes 576 checks.
 *
 * ⚖⚖ THE ROWS CARRY NO VALUES, AND THAT IS THE RULING. ARCHITECT: *"if we can use an autogenerated enum
 * id let's do a; if we have to specify it and maintain the numbering by hand then we can only do b,
 * because the indexing of the array is not possible via discontinuous enum values."* They can be, so the
 * language deals out 0, 1, 2 … in the order it meets them and no number is ever typed.
 *
 * ⭐ WHAT THAT BUYS IS NOT TIDINESS, IT IS THREE FAILURES THAT STOP BEING POSSIBLE. A row cannot be
 * numbered past the end of the array, because nobody numbers it. Two rows cannot share a seat, for the
 * same reason. And the seats cannot be discontinuous, which is the one an indexed array cannot survive.
 * ⇒ A generated check guarding all three would have nothing left to catch, so there is none: the
 * property is held by the mechanism rather than watched for by a rule beside it.
 *
 * ⚖⚖ AND THIS LIST IS `sys`'s ALONE AND IS NOT MEANT TO GROW FOR ANYBODY ELSE. ARCHITECT: *"this also
 * means that we do not need to keep the enum list extensible, which is arguably good for this kind of
 * system register thing."* A second package does not get a row here; it gets its own entry behind the
 * extension hatch below.
 * ⭐ AND THAT IS WHAT KEEPS THE SEATS SAFE TO HAND OUT, which matters because a row's number is
 * something a composed program holds. A list that merged every package's rows would deal them in roster
 * order, so one package adding a row moves every seat belonging to every package after it — and a
 * program written against the old numbering then reads the wrong row with nothing failing to build.
 * One package's rows in here and everyone else behind one door means `sys` can only ever move `sys`'s
 * seats, and nothing outside is numbered at all.
 * ────────────────────────────────────────────────────────────────────────────────────────────────── */
#define SYS__SYSTEM_REGISTER__LIST(X)                                                                 \
    /* WHERE EVERY BLOCK'S COMPUTING BASE IS. A REFERENCE: the heap offset of one allocation          \
     * holding the bases end to end, so block N's is that offset plus N. ⚖ RULED indexed by the       \
     * block id, and it is a plain indexed array rather than a list — one slot per block, sized       \
     * once, never resized, so every reason a list exists is absent and the lookup is an addition. */ \
    X(SYS__SYSTEM_REGISTER__COMPUTING_BASE_ARRAY)                                                     \
    /* WHERE EVERY BLOCK'S MESSAGES ARRIVE. A REFERENCE, and the same shape as the bases: one slot    \
     * per block, sized once at boot. What differs is what a slot HOLDS — not a thing but a LIST, so  \
     * posting to a block is adding to a list, which needs no room found at the posting end and no    \
     * protocol of its own. ⚖ ARCHITECT: a message is *"most likely"* an object reference to a heap   \
     * object — which is where this is going, and not something decided.                              \
     * ⛔ THE ROW IS THE WHOLE OF WHAT EXISTS. Nothing stands the array up, nothing posts to it and    \
     * nothing drains it. It is here because a mailbox is the second thing no scope can own — a block \
     * with its own copy of its mailbox is a block nobody can reach. */                               \
    X(SYS__SYSTEM_REGISTER__MAILBOX_ARRAY)                                                            \
    /* WHERE EVERY OTHER PACKAGE KEEPS ITS OWN. A REFERENCE to one entry per package, indexed by the  \
     * package id — so a package reaches its own entry point by knowing who it is, which it always    \
     * does. ⚖ ARCHITECT: *"add a system register called extension_hatch which can be either an array \
     * or a list ... the package can find its index and have an entry point without polluting the     \
     * register."*                                                                                    \
     * ⛳ AND IT IS ONE ROW WHATEVER ARRIVES, which is the whole of what it buys: a package needing    \
     * device-wide state of its own puts it behind its own entry and this list never learns about it. \
     * The boot stands it up, `package_count` entries long, before any package's init runs. */         \
    X(SYS__SYSTEM_REGISTER__EXTENSION_HATCH)                                                          \
    /* THE THREE TABLES A NAME IS REGISTERED IN, each a REFERENCE to a dictionary. ⚖ ARCHITECT: the   \
     * symbol table gets a row, *"also the hash2string and the string2symbol should have their own     \
     * entry"* — one string per text and one number per string are two jobs, and a setting's value is \
     * text that is not a name. They are system-wide, not a block's: a name means one thing on a       \
     * machine. `sys`'s init stands all three up; `symbol.cuh` is what reads and writes them.          \
     * ⚠ WRITTEN AFTER THE BLOCKS START, which the rule above this list does not cover — `REASONED`   \
     * safe on the premise that the launch standing the packages up is the only one running, and that \
     * nothing writes these rows again while the machine is up. */                                    \
    X(SYS__SYSTEM_REGISTER__HASH_TO_STRING)                                                           \
    X(SYS__SYSTEM_REGISTER__STRING_TO_SYMBOL)                                                         \
    X(SYS__SYSTEM_REGISTER__SYMBOL_TO_STRING)                                                         \
    /* THE BOOT'S OWN PARAMETERS, a REFERENCE to a SEALED dictionary of key-hash → value string.      \
     * ⚖ ARCHITECT: *"the boot process can create the string object, pass it to the config2dict,      \
     * obtain the address and i think it is correct to set it in the system register … it is read by  \
     * the init setups as those are the boot parameters."*                                            \
     * ⭐ IT IS THE SAME SHAPE AS THE THREE ABOVE — written once, never again, read by whoever — and   \
     * that is the argument for a row rather than an argument: an init handed its settings could only \
     * keep what it was given, and a later reader (a second stage, a verb, the pool re-reading its     \
     * sizing) would have no way back to them.                                                        \
     * ⛳ WHAT MAKES IT SAFE TO PUBLISH IS THE SEAL, NOT THE HIDING: a sealed dictionary is read with  \
     * no lock, which is what the async compute needs anyway. The row itself stays writable like       \
     * every other — ⚖ *"it might even be correct to have it modifiable, if someone wants to load a    \
     * new config."*                                                                                  \
     * ⛔ AND IT IS WRITTEN EARLIER THAN THE THREE ABOVE: the STANDUP KERNEL sets it in C, before it   \
     * builds the init list, because ⚖ the constraint is ORDERING and not ownership — *"i dont mind it \
     * can be the boot's c as well … as long as it happens before the other opcodes"* — and the kernel \
     * is the only thing that runs after the register exists, before any init, AND is handed the text  \
     * as an argument. A call with no arguments cannot be given a string.                              \
     * ⛳ NO CONFIG FILE STILL WRITES ONE, EMPTY, so an init has ONE failure mode. */                   \
    X(SYS__SYSTEM_REGISTER__SETTINGS)

/* The seats, dealt in the order the list is read. */
enum {
#define SYS__SYSTEM_REGISTER__ROW(NAME) NAME,
    SYS__SYSTEM_REGISTER__LIST(SYS__SYSTEM_REGISTER__ROW)
#undef SYS__SYSTEM_REGISTER__ROW
    /* Not a row. The seat after the last one, which is how many there are — and the array's size. */
    SYS__SYSTEM_REGISTER__ROWS
};

/* Asked for a row this register has no seat for. Every verb of the register refuses the same way, and the refusal
 * is loud because there is no sensible answer to give: a row out of range is a caller naming something
 * that does not exist, and answering zero would let it carry on believing it does. */
/* How many nodes a placed register comes to: one per row and one for the head the rows hang off.
 * ⛳ DERIVED FROM THE ROW LIST, in the one file that owns the shape, so the size exists without anybody
 * counting rows by hand. ⛔ AND NOTHING READS IT. The boot reserves a whole chunk-wide slot per placed
 * object instead — arithmetic in the heap's geometry rather than in rows, argued where it is written —
 * so the two sizes answer different questions and neither checks the other: a register whose rows
 * outgrew a chunk would be placed in a slot too small to hold them and nothing would say.
 * `REASONED`, from that reservation and the placing it feeds. */
#define SYS__SYSTEM_REGISTER__NODES ((uint64_t)SYS__SYSTEM_REGISTER__ROWS + 1ull)

#define SYS__SYSTEM_REGISTER__FAULT_NO_ROW 0x53524E52ull   /* "SRNR" */
/* Asked anything at all before the boot stood the register up. It is a different mistake from naming a
 * row that does not exist — one is a caller counting wrong, the other is a launch that has not started —
 * and a log carries only the word, so they cannot share one. */
#define SYS__SYSTEM_REGISTER__FAULT_NOT_PUBLISHED 0x53524E50ull   /* "SRNP" */

#endif /* SILVANN__PACKAGES_SYS_CONTRACTS_OBJECTS_SYSTEM_REGISTER_CUH */
