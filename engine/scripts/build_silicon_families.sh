#!/usr/bin/env bash
# Build one binary per silicon family — `libsilvann_amd_rocm6_wave64.so` and `libsilvann_nvidia_cuda12.so` —
# into build/silicon_families/.
#
# ⚖ *"the gpu side becomes a separate binary that is loaded at the start of the cpu session"* · *"we
# build for all architectures"*. Each is ONE translation unit, compiled by its own family's toolchain: the
# family's answers, every package's card side written against them, and `silvann_silicon_family_get`. ▶ contracts/abi/silicon_family.cuh.
#
# ⛳ THE TRANSLATION UNIT IS GENERATED, NOT CHECKED IN, for the reason setup.py gives for the compute TU:
#   it is a dozen includes and nothing else, and `one_tu` holds src/ to exactly one .cu.
# ⛳ A FAMILY NEEDS NO DEVICE TO BE BUILT, only its compiler. `nvcc` builds the CUDA one on a box with
#   no NVIDIA card; `SILVANN_NVCC` names it, else PATH, else the toolchain unpacked beside the repo.
#
#   SILVANN_SILICON_FAMILIES  which to build      default every family on the roster but the host
#   SILVANN_HIP_ARCHES     narrows amd_rocm6_wave64's gfx targets, for a faster development build
#   SILVANN_CUDA_ARCHES    narrows nvidia_cuda12's sm numbers; the last is also carried as PTX
#   — each family's targets are otherwise its own `includes.cuh` row, and a narrowed binary is not one to ship
set -u
cd "$(dirname "$0")/.." || exit 2
OUT=build/silicon_families
mkdir -p "$OUT"
FAILED=0

# a build's failure, said: its compiler's errors — nvcc's "fatal" lines too (an architecture it does not build) — or,
#   where none matched, the log's last lines, so "⛔ family:" never stands alone (a tester's nvcc 13.4 and sm_61, 2026-10-21)
reason() {   # log
    grep -m10 -iE 'error|fatal' "$1" || tail -n 5 "$1"
}

# ⭐ OPENCL NEEDS NOTHING INSTALLED TO BE BUILT (⚖ 2026-10-21 "why dont we build opencl2 and opencl 1 automatically so
#   there is nothing no one needs to do?"): the headers are Khronos' own, carried (scripts/third_party/OpenCL-Headers, as
#   build.py does on Windows), and the families link against a stub `libOpenCL.so.1` made here from `cl.h`'s own calls —
#   the SONAME every OpenCL loader carries, so the library names the loader as linking the real one would. The machine's
#   own loader (ocl-icd, ROCm's, NVIDIA's) is what runs; where there is none the family does not load, and the others run.
#   SILVANN_OPENCL_INCLUDE / SILVANN_OPENCL_LIB name others.
opencl_link() {   # sets CLINC and CLLIB
    CLINC=${SILVANN_OPENCL_INCLUDE:-scripts/third_party/OpenCL-Headers}
    CLLIB=${SILVANN_OPENCL_LIB:-}
    [ -f "$CLINC/CL/cl.h" ] || return 1
    [ -n "$CLLIB" ] && return 0
    CLLIB=$OUT/opencl_loader_stub
    [ -f "$CLLIB/libOpenCL.so" ] && return 0
    mkdir -p "$CLLIB"
    # ⛳ the names as build.py reads them: `CL_API_CALL` and the name are on two lines in Khronos' cl.h
    python3 -c 'import re, sys; print("".join("void %s(void) {}\n" % n for n in sorted(set(re.findall(r"CL_API_CALL\s+(cl\w+)\s*\(", open(sys.argv[1]).read())))), end="")' \
        "$CLINC/CL/cl.h" > "$CLLIB/stub.c" || return 1
    [ -s "$CLLIB/stub.c" ] || return 1     # an empty stub links nothing, and the families would not name the loader
    gcc -shared -fPIC -Wl,-soname,libOpenCL.so.1 -o "$CLLIB/libOpenCL.so" "$CLLIB/stub.c" > "$CLLIB/stub.log" 2>&1
}

# ⛳ A FAMILY'S TRANSLATION UNIT IS ITS OWN `unit.cuh`; the `.cu` written here is the one line that
#   includes it, because `one_tu` holds src/ to exactly one `.cu`.
tu() {   # family
    printf '/* GENERATED BY scripts/build_silicon_families.sh — do not edit, and do not check in. */\n#include "silicon_families/%s/unit.cuh"\n' "$1"
}

# ⭐ A FAMILY IS BUILT FOR THE CARDS IT INCLUDES, read from the targets row of its own `includes.cuh`, so
#   the list that decides which cards a family takes and the list its binary has code for are one list.
targets() {   # family · row macro
    grep -E "^#define $2\(X\)" "src/silicon_families/$1/includes.cuh" | grep -oE 'X\([a-z0-9_]+\)' | sed -E 's/X\((.*)\)/\1/'
}

# ⛳ THE PHANTOM GCC DIR — ▶ setup.py. A `libstdc++-N-dev` can sit above the real toolchain with no
#   `cc1plus`, and clang picks it and fails with `'cmath' file not found`.
GCC=""
for d in /usr/lib/gcc/x86_64-linux-gnu/*/; do [ -f "$d/cc1plus" ] && GCC="$d"; done

# ⛳ A FAMILY IS BUILT WHEN IT EXISTS AND EXPORTS EXACTLY ONE FUNCTION OF ITS OWN: `silvann_silicon_family_get`.
#   Its doors reach the program through the table that answers, so a door visible by name would be a
#   second way in — and the way a program would come to depend on a name instead of a list. The vendor
#   runtime a family links statically may export its own; only our `<prefix>__` names are counted against it.
built() {   # name · file
    if [ ! -f "$2" ] || ! nm -D --defined-only "$2" | grep -qw silvann_silicon_family_get; then
        echo "⛔ $1 did not build, or does not export silvann_silicon_family_get"; FAILED=1; return; fi
    local leaked; leaked=$(nm -D --defined-only "$2" | awk '{print $3}' | grep -cE '^[a-z][a-z0-9_]*__')
    if [ "$leaked" != "0" ]; then echo "⛔ $1 exports $leaked package symbol(s) beside its entry"; FAILED=1; return; fi
    echo "✅ $1 -> $2 ($(stat -c %s "$2") bytes), one entry point and nothing else of ours"
}

# ⛳ EVERY FAMILY ON THE ROSTER BUT THE HOST, which is compiled into the program.
ALL=$(grep -oE '^[[:space:]]*X\([0-9]+u,[[:space:]]*[A-Z0-9_]+,[[:space:]]*[a-z0-9_]+' src/silicon_families/roster.cuh \
      | sed -E 's/.*,[[:space:]]*//' | grep -vx host | paste -sd,)
for P in $(echo "${SILVANN_SILICON_FAMILIES:-$ALL}" | tr ',' ' '); do
    # ⭐ A FAMILY THAT DOES NOT ANSWER EVERY PACKAGE IS SKIPPED, NOT A FAILED BUILD. ⚖ *"can we skip that
    #   family without collapsing the build (and maybe log that the function x was missing)?"* Asked before
    #   compiling, by the same reading the claim gate uses; the reason is left beside where the binary would
    #   be, and the wheel reads it, so `cards()` says why the card went to another family or to none.
    rm -f "$OUT/libsilvann_$P.skipped"
    if [ -d "src/silicon_families/$P" ]; then
        GAPS=$(python3 scripts/silicon_family_unanswered.py "$P"); RC=$?
        if [ $RC -eq 1 ]; then
            rm -f "$OUT/libsilvann_$P.so"
            WHY="not built: it does not answer $(echo $GAPS | sed 's/ /, /g')"
            echo "$WHY" > "$OUT/libsilvann_$P.skipped"
            echo "⚠ $P skipped — $WHY"
            continue
        elif [ $RC -ne 0 ]; then echo "⛔ $P: could not read what it answers"; FAILED=1; continue; fi
    fi
    # ⛳ nn's arithmetic dial (`nn/contracts/defaults.cuh`), overridden for a measurement; the generator
    #   of the OpenCL kernels reads the same variable.
    NNDIAL=${SILVANN_NN_ARITHMETIC_FAST:+-DNN__ARITHMETIC__FAST=$SILVANN_NN_ARITHMETIC_FAST}
    case "$P" in
    amd_rocm6_wave64)
        tu amd_rocm6_wave64 > "$OUT/amd_rocm6_wave64.cu"
        WANT=$(targets amd_rocm6_wave64 AMD_ROCM6_WAVE64__TARGETS | paste -sd,)
        ARCHES=""; for a in $(echo "${SILVANN_HIP_ARCHES:-$WANT}" | tr ',' ' '); do
            ARCHES="$ARCHES --offload-arch=$a"; done
        rm -f "$OUT/libsilvann_amd_rocm6_wave64.so"
        # shellcheck disable=SC2086
        /opt/rocm/bin/hipcc ${GCC:+--gcc-install-dir=$GCC} $ARCHES $NNDIAL -O2 -std=c++17 -fPIC -shared -fvisibility=hidden -I src \
            "$OUT/amd_rocm6_wave64.cu" -o "$OUT/libsilvann_amd_rocm6_wave64.so" > "$OUT/amd_rocm6_wave64.log" 2>&1 \
            || { echo "⛔ amd_rocm6_wave64:"; reason "$OUT/amd_rocm6_wave64.log"; }
        built amd_rocm6_wave64 "$OUT/libsilvann_amd_rocm6_wave64.so" ;;
    nvidia_cuda12)
        NVCC=${SILVANN_NVCC:-$(command -v nvcc || echo "$(cd .. && pwd)/toolchains/cuda-12.9/bin/nvcc")}
        [ -x "$NVCC" ] || { echo "⛔ nvidia_cuda12: no nvcc (set SILVANN_NVCC)"; FAILED=1; continue; }
        tu nvidia_cuda12 > "$OUT/nvidia_cuda12.cu"
        WANT=$(targets nvidia_cuda12 NVIDIA_CUDA12__TARGETS | sed 's/^sm_//' | paste -sd,)
        GENCODE=""; LAST=""
        for a in $(echo "${SILVANN_CUDA_ARCHES:-$WANT}" | tr ',' ' '); do
            GENCODE="$GENCODE -gencode arch=compute_$a,code=sm_$a"; LAST=$a; done
        GENCODE="$GENCODE -gencode arch=compute_$LAST,code=compute_$LAST"
        rm -f "$OUT/libsilvann_nvidia_cuda12.so"
        # ⛳ `-cudart static` IS nvcc's DEFAULT AND IT IS WRITTEN ANYWAY: the CUDA runtime goes inside the
        #   family, so the box it lands on needs only the driver, not a toolkit.
        # shellcheck disable=SC2086
        "$NVCC" $GENCODE $NNDIAL -O2 -std=c++17 -cudart static -Xcompiler -fPIC,-fvisibility=hidden -shared -I src \
            "$OUT/nvidia_cuda12.cu" -o "$OUT/libsilvann_nvidia_cuda12.so" > "$OUT/nvidia_cuda12.log" 2>&1 \
            || { echo "⛔ nvidia_cuda12:"; reason "$OUT/nvidia_cuda12.log"; }
        built nvidia_cuda12 "$OUT/libsilvann_nvidia_cuda12.so" ;;
    khronos_opencl2)
        # ⛳ NO CARD COMPILER: the kernels are OpenCL C, generated from nn's rows and compiled by the runtime
        #   on the card it finds. What is built here is the host side, against the OpenCL loader.
        opencl_link || { echo "⛔ khronos_opencl2: no CL/cl.h under $CLINC, or the loader's stub would not build"; FAILED=1; continue; }
        python3 scripts/opencl_kernel_source.py "$OUT/khronos_opencl2_kernels.cpp" \
            || { echo "⛔ khronos_opencl2: nn's kernels would not become OpenCL C"; FAILED=1; continue; }
        tu khronos_opencl2 > "$OUT/khronos_opencl2.cpp"
        rm -f "$OUT/libsilvann_khronos_opencl2.so"
        g++ -O2 -std=c++17 -fPIC -shared -fvisibility=hidden -I src -I "$CLINC" \
            "$OUT/khronos_opencl2.cpp" "$OUT/khronos_opencl2_kernels.cpp" \
            -L "$CLLIB" -lOpenCL -lpthread -o "$OUT/libsilvann_khronos_opencl2.so" \
            > "$OUT/khronos_opencl2.log" 2>&1 \
            || { echo "⛔ khronos_opencl2:"; reason "$OUT/khronos_opencl2.log"; }
        built khronos_opencl2 "$OUT/libsilvann_khronos_opencl2.so" ;;
    khronos_opencl1_igpu)
        # ⛳ AS khronos_opencl2, NO CARD COMPILER — the kernels are OpenCL C 1.2, every pointer's space worked out by the
        #   generator — against the carried headers and the loader's stub (▶ `opencl_link`).
        opencl_link || { echo "⛔ khronos_opencl1_igpu: no CL/cl.h under $CLINC, or the loader's stub would not build"; FAILED=1; continue; }
        python3 scripts/opencl1_kernel_source.py "$OUT/khronos_opencl1_igpu_kernels.cpp" \
            || { echo "⛔ khronos_opencl1_igpu: nn's kernels would not become OpenCL C 1.2"; FAILED=1; continue; }
        tu khronos_opencl1_igpu > "$OUT/khronos_opencl1_igpu.cpp"
        rm -f "$OUT/libsilvann_khronos_opencl1_igpu.so"
        g++ -O2 -std=c++17 -fPIC -shared -fvisibility=hidden -I src -I "$CLINC" \
            "$OUT/khronos_opencl1_igpu.cpp" "$OUT/khronos_opencl1_igpu_kernels.cpp" \
            -L "$CLLIB" -lOpenCL -lpthread -o "$OUT/libsilvann_khronos_opencl1_igpu.so" \
            > "$OUT/khronos_opencl1_igpu.log" 2>&1 \
            || { echo "⛔ khronos_opencl1_igpu:"; reason "$OUT/khronos_opencl1_igpu.log"; }
        built khronos_opencl1_igpu "$OUT/libsilvann_khronos_opencl1_igpu.so" ;;
    x86_avx2)
        # ⛳ THE CPU: g++ for the instruction set the family's name promises — the bodies and the overrides are
        #   compiled for AVX2, FMA and F16C, and the family counts no device on a processor without them.
        tu x86_avx2 > "$OUT/x86_avx2.cpp"
        rm -f "$OUT/libsilvann_x86_avx2.so"
        g++ $NNDIAL -O3 -mavx2 -mfma -mf16c -std=c++17 -fPIC -shared -fvisibility=hidden -I src \
            "$OUT/x86_avx2.cpp" -lpthread -o "$OUT/libsilvann_x86_avx2.so" \
            > "$OUT/x86_avx2.log" 2>&1 \
            || { echo "⛔ x86_avx2:"; reason "$OUT/x86_avx2.log"; }
        built x86_avx2 "$OUT/libsilvann_x86_avx2.so" ;;
    *) echo "⛔ $P: this script has no recipe for it — which compiler, and how its targets are passed"; FAILED=1 ;;
    esac
done

# ⛳ THERE IS NO SECOND COPY OF nn's DOORS TO CHECK AGAINST: they are written once, in
#   `src/packages/nn/gpu/doors.cuh`, and every family compiles that file against its own launch.
exit $FAILED
